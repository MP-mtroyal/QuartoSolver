# HELPER for loadData
#
# Combines all solution files for a given depth into one file.
#
# Specifically, this function:
#   - Loads existing solutions from Agl_Level_<depth>_solved.txt
#   - Merges additional valid solutions from:
#       • Agl_Level_<depth>_chunk*_to_*.txt (valid only)
#       • Agl_Level_<depth>_chunk*_CudaSolved*.txt (may include partials)
#   - Ensures no duplicate solutions (preserves existing entries)
#   - Saves the final combined result into Agl_Level_<depth}_solved.txt
#
# Args:
#   folder (str): Directory containing the solution files
#   depth (int): Depth level of the solution files to combine
#
# Returns:
#   None. Saves merged solutions to disk.
# ------------------------------------------------------------
def combine_solution_files(folder, depth):
    print("Combining solution files...")
    combined_solutions = {}

    # Load existing solutions first (if they exist)
    solved_file = os.path.join(folder, f"Agl_Level_{depth}_solved.txt")
    print(f'Found solved file {solved_file}')
    if os.path.exists(solved_file):
        existing_loader = DepthSaver()
        existing_loader.loadGames(fileName=os.path.basename(solved_file), path=folder + "/")
        combined_solutions.update(dict(zip(existing_loader.hashes, existing_loader.solutions)))

    # Then, load backpropagated solutions if available
    backprop_file = os.path.join(folder, f"Agl_Level_{depth}_backprop_solved.txt")
    if os.path.exists(backprop_file):
        print(f'Found backprop file {backprop_file}')
        loader = DepthSaver()
        loader.loadGames(fileName=os.path.basename(backprop_file), path=folder + "/")
        for h, s in zip(loader.hashes, loader.solutions):
            if h not in combined_solutions:
                combined_solutions[h] = s

    # Then, load _to_ files (they only contain valid solutions)
    for file in sorted(os.listdir(folder)):
        # if file.startswith(f"Agl_Level_{depth}_chunk") and "_to_" in file: # TODO: for GPU parallelism
        if file.startswith(f"CPU_Level_{depth}_chunk") and "_to_" in file: # for CPU parallelism
            print(f'Found chunk file {file}')
            loader = DepthSaver()
            loader.loadGames(fileName=file, path=folder + "/")
            for h, s in zip(loader.hashes, loader.solutions):
                if h not in combined_solutions:
                    combined_solutions[h] = s

    # Save the merged solutions
    saver = DepthSaver()
    saver.hashes = list(combined_solutions.keys())
    saver.solutions = list(combined_solutions.values())
    saver.saveSolution(f"Agl_Level_{depth}_solved.txt", path=folder + "/")

    print(f"Merged solutions saved to {solved_file}. Total unique solved boards: {len(combined_solutions)}")

# ------------------------------------------------------------
# HELPER for loadData
#
# Loads solved board hashes and their associated solution strings
# from a .txt file (generated by DepthSaver).
# 
# Returns:
#   A dictionary mapping board hash → solution string
#   Example: {123456789: "AD2", ...}
# ------------------------------------------------------------
def parse_solutions(file_path):
    print(f"Parsing {file_path}...")
    loader = DepthSaver()
    loader.loadGames(fileName=os.path.basename(file_path), path=os.path.dirname(file_path) + "/")
    return dict(zip(loader.hashes, loader.solutions))

