def convert_txt_to_lmdb_binary_keys(txt_path, lmdb_path):
    os.makedirs(os.path.dirname(lmdb_path), exist_ok=True)
    env = lmdb.open(lmdb_path, map_size=5 * 1024**3)  # Up to 1TB

    with env.begin(write=True) as txn, open(txt_path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line or ',' not in line:
                continue
            key_str, value = line.split(',', 1)
            try:
                key_int = int(key_str)
                key_bytes = struct.pack('>Q', key_int)
                txn.put(key_bytes, value.encode('ascii'))
            except ValueError:
                continue  # Skip malformed lines

    env.sync()
    print(f"LMDB written to {lmdb_path} with binary 8-byte keys.")

class LMDBSolutionDict:
    def __init__(self, path):
        self.env = lmdb.open(path, readonly=True, lock=False, max_readers=2048)
        self.txn = self.env.begin()

    def __getitem__(self, key: int) -> str:
        key_bytes = struct.pack('>Q', key)
        val = self.txn.get(key_bytes)
        if val is None:
            raise KeyError(key)
        return val.decode('ascii')

    def __contains__(self, key: int) -> bool:
        key_bytes = struct.pack('>Q', key)
        return self.txn.get(key_bytes) is not None

    def get(self, key: int, default=None) -> str:
        key_bytes = struct.pack('>Q', key)
        val = self.txn.get(key_bytes)
        return val.decode('ascii') if val else default

class LMDBSet:
    def __init__(self, path):
        self.env = lmdb.open(path, readonly=True, lock=False)
        self.txn = self.env.begin()

    def __contains__(self, key: int) -> bool:
        key_bytes = struct.pack('>Q', key)
        return self.txn.get(key_bytes) is not None

